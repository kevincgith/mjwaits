// Regenerates src/lib/testHands.ts - the hidden "Test hands" sheet's list
// (tap the MJWaits logo 5 times) - from the scoring tests:
//
//   node scripts/extract-test-hands.mjs
//
// Every `scoreHand("<notation>", ctx({...}))` call in src/lib/scoring.test.ts
// that isn't expected to throw becomes one entry, labelled with the test
// that uses it and grouped by its describe() block. Only plain-literal ctx
// overrides are carried over (booleans, numbers, strings and a
// `{ suit, rank }` winning tile) - which is every override the tests use
// today. src/lib/testHands.test.ts checks that each entry still scores.

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = await readFile(path.join(root, "src/lib/scoring.test.ts"), "utf8");

// Walk describe / it / scoreHand in source order, remembering the latest
// describe and it titles as the labels for each hand found after them.
const token =
  /\bdescribe\(\s*"((?:[^"\\]|\\.)*)"|\bit\(\s*"((?:[^"\\]|\\.)*)"|(\(\)\s*=>\s*)?\bscoreHand\(\s*"([^"]+)"\s*,\s*ctx\(([^)]*(?:\{[^}]*\}[^)]*)*)\)/g;

function parseOverrides(text) {
  const body = text.trim().replace(/^\{/, "").replace(/\}$/, "").trim();
  if (body === "") return {};
  const out = {};
  const pair = /(\w+)\s*:\s*(\{[^}]*\}|"[^"]*"|true|false|-?\d+)/g;
  let m;
  let consumed = "";
  while ((m = pair.exec(body)) !== null) {
    const [whole, key, raw] = m;
    consumed += whole;
    if (raw.startsWith("{")) {
      const suit = /suit:\s*"([mtbz])"/.exec(raw)?.[1];
      const rank = /rank:\s*(\d)/.exec(raw)?.[1];
      if (!suit || !rank) return null;
      out[key] = { suit, rank: Number(rank) };
    } else {
      out[key] = JSON.parse(raw);
    }
  }
  // Anything not understood (a computed value, a helper call) - skip the
  // whole hand rather than load it with half its situation.
  const leftover = body.replace(pair, "").replace(/[\s,]/g, "");
  return leftover === "" ? out : null;
}

let describeTitle = "";
let itTitle = "";
const seen = new Set();
const entries = [];
let skipped = 0;
let match;
while ((match = token.exec(source)) !== null) {
  const [, describeName, itName, throwsArrow, hand, ctxText] = match;
  if (describeName !== undefined) {
    describeTitle = describeName;
    continue;
  }
  if (itName !== undefined) {
    itTitle = itName;
    continue;
  }
  if (throwsArrow) continue; // `expect(() => scoreHand(...)).toThrow()` - not a winning hand
  const ctx = parseOverrides(ctxText);
  if (ctx === null) {
    skipped++;
    continue;
  }
  const key = hand + JSON.stringify(ctx);
  if (seen.has(key)) continue;
  seen.add(key);
  entries.push({ group: describeTitle, name: itTitle, hand, ctx });
}

const out = `// GENERATED by scripts/extract-test-hands.mjs from src/lib/scoring.test.ts -
// don't edit by hand; rerun the script after changing the scoring tests.
//
// The hidden "Test hands" sheet's list (tap the MJWaits logo 5 times): each
// winning hand the scoring tests score, with the situation that test sets.

import type { GameContext } from "./scoring";

export interface TestHand {
  /** The describe() block the test sits in. */
  group: string;
  /** The test's own name. */
  name: string;
  /** Scoring notation - "(123m)" a declared meld, the rest concealed. */
  hand: string;
  /** The test's ctx() overrides, on top of the defaults. */
  ctx: Partial<GameContext>;
}

/** scoring.test.ts's ctx() defaults - every entry's ctx is on top of these. */
export const TEST_HAND_BASE_CONTEXT: GameContext = {
  seatWind: 1,
  roundWind: 1,
  selfDraw: false,
  winningTile: null,
  riichi: "none",
  instantWin: false,
  eatRiichi: false,
  earlyWin: "none",
  multiWin: "none",
  heavenlyWin: "none",
  lastTileWin: "none",
  flowerDraw: 0,
  kongDraw: 0,
  robKong: 0,
  dealerStreak: 0,
  manualVisibleTripleWin: false,
  manualVisibleExhaustedMultiWait: false,
};

export const TEST_HANDS: TestHand[] = ${JSON.stringify(entries, null, 2)};
`;
await writeFile(path.join(root, "src/lib/testHands.ts"), out);
console.log(`wrote ${entries.length} hands (${skipped} skipped for non-literal ctx)`);
